"""Reproduce the DataChannel-only subset of aiortc 1.15.0.

Run with a source checkout or an installed upstream package, never at runtime.
The generated source retains upstream ICE / DTLS / SCTP logic and its license;
audio/video negotiation, codecs, RTP routing and SRTP sessions are omitted.
See hookup/_rtc/README.md for the compatibility and maintenance constraints.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = (
    'clock.py', 'exceptions.py', 'rtcconfiguration.py', 'rtcdatachannel.py',
    'rtcicetransport.py', 'rtcrtpparameters.py', 'rtcsctptransport.py',
    'rtcsessiondescription.py', 'stats.py', 'utils.py', 'sdp.py',
    'rtcpeerconnection.py', 'rtcdtlstransport.py',
)
HEADER = ('# Derived from aiortc 1.15.0, Copyright (c) Jeremy Lainé.\n'
          '# BSD-3-Clause; see LICENSE and UPSTREAM.json in this directory.\n'
          '# Generated by scripts/vendor_rtc_datachannel.py; see README.md.\n')


class DataOnlyPeer(ast.NodeTransformer):
    """Remove media branches structurally, leaving data transport unchanged."""
    DROP = {
        'filter_preferred_codecs', 'find_common_codecs',
        'find_common_header_extensions', 'is_codec_compatible',
        'create_media_description_for_transceiver', 'and_direction',
        'or_direction', 'reverse_direction', '__assertTrackHasNoSender',
        '__createTransceiver', '__getTransceiverByMid',
        '__getTransceiverByMLineIndex', '__localRtp', '__remoteRtp',
        'getReceivers', 'getSenders', 'getTransceivers',
    }

    def visit_Import(self, node):
        node.names = [n for n in node.names if n.name not in {'copy', 'uuid'}]
        return node if node.names else None

    def visit_ImportFrom(self, node):
        if node.module in {'codecs', 'events', 'mediastreams', 'rtcrtpreceiver',
                           'rtcrtpsender', 'rtcrtptransceiver', 'rtcrtpparameters'}:
            return None
        if node.module is None:
            node.names = [n for n in node.names if n.name != 'rtp']
        if node.module == 'rtcconfiguration':
            node.names = [n for n in node.names if n.name != 'RTCBundlePolicy']
        if node.module == 'exceptions':
            node.names = [n for n in node.names if n.name != 'OperationError']
        return node

    def visit_FunctionDef(self, node):
        if node.name in self.DROP:
            return None
        if node.name in {'addTrack', 'addTransceiver'}:
            node.args = ast.parse('def method(self, *args, **kwargs): pass').body[0].args
            node.returns = None
            node.body = ast.parse('raise NotImplementedError("Only data channels are supported")').body
            return node
        node = self.generic_visit(node)
        if node.name == '__createDtlsTransport':
            # There is exactly one application m-line, so no RTP transport or
            # BUNDLE reuse can occur. Keep the original event/state wiring.
            first = next(i for i, n in enumerate(node.body)
                         if isinstance(n, ast.Expr) and
                         'iceGatherer.on' in ast.unparse(n))
            node.body = ast.parse('iceGatherer = RTCIceGatherer(iceServers=self.__configuration.iceServers)').body + node.body[first:]
        elif node.name == '__createSctpTransport':
            first = next(i for i, n in enumerate(node.body)
                         if isinstance(n, ast.Assign) and
                         ast.unparse(n.targets[0]) == 'self.__sctp')
            node.body = ast.parse('dtlsTransport = self.__createDtlsTransport()\nbundled = False').body + node.body[first:]
        elif node.name == '__validate_description':
            guard = ast.parse('if len(description.media) != 1 or description.media[0].kind != "application":\n    raise ValueError("Exactly one data-channel application section is required")').body
            node.body = guard + node.body
        elif node.name == 'getStats':
            node.body = ast.parse('merged = RTCStatsReport()\nfor transport in self.__dtlsTransports:\n    merged.update(transport._get_stats())\nreturn merged').body
        return node

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_For(self, node):
        iterator = ast.unparse(node.iter)
        if '__transceivers' in iterator or 'getTransceivers()' in iterator or iterator == 'trackEvents':
            return None
        return self.generic_visit(node)

    def visit_If(self, node):
        condition = ast.unparse(node.test)
        if "in ['audio', 'video']" in condition:
            # The outer SDP validation rejects these sections before any
            # transport changes. Keep only the application branch.
            result = []
            for n in node.orelse:
                value = self.visit(n)
                if isinstance(value, list): result.extend(value)
                elif value is not None: result.append(value)
            return result
        if condition == 'bundle and bundle.items':
            return None
        return self.generic_visit(node)

    def visit_Assign(self, node):
        if any(ast.unparse(t) in {'self.__cname', 'self.__stream_id', 'MEDIA_KINDS'} for t in node.targets):
            return None
        if any(ast.unparse(t) in {'trackEvents', 'bundle'} for t in node.targets):
            # Keep locally constructed BUNDLE groups; omit only remote media
            # transport coalescing (which requires multiple m-lines).
            if ast.unparse(node.value).startswith('next(') or ast.unparse(node.targets[0]) == 'trackEvents':
                return None
        return self.generic_visit(node)

    def visit_AnnAssign(self, node):
        target = ast.unparse(node.target)
        if target == 'self.__transceivers':
            return None
        if target in {'self.__remoteDtls', 'self.__remoteIce'}:
            value = 'dict[RTCSctpTransport, RTCDtlsParameters]' if target.endswith('Dtls') else 'dict[RTCSctpTransport, RTCIceParameters]'
            node.annotation = ast.parse(value, mode='eval').body
        return self.generic_visit(node)


class DataOnlyDtls(ast.NodeTransformer):
    DROP = {'RtpReceiver', 'RtpSender', 'RtpRouter', '_setup_srtp',
            '_handle_rtcp_data', '_handle_rtp_data', '_register_rtp_receiver',
            '_register_rtp_sender', '_send_rtp', '_unregister_rtp_receiver',
            '_unregister_rtp_sender'}

    def visit_Import(self, node):
        node.names = [n for n in node.names if n.name != 'pylibsrtp']
        return node if node.names else None

    def visit_ImportFrom(self, node):
        if node.module in {'pylibsrtp', 'rtp', 'rtcrtpparameters'}:
            return None
        if node.module is None:
            node.names = [n for n in node.names if n.name != 'rtp']
        return node

    def visit_ClassDef(self, node):
        return None if node.name in self.DROP else self.generic_visit(node)

    def visit_FunctionDef(self, node):
        return None if node.name in self.DROP else self.generic_visit(node)

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_Assign(self, node):
        targets = [ast.unparse(t) for t in node.targets]
        if any(t.startswith(('self._rtp_', 'self._rx_srtp', 'self._tx_srtp')) for t in targets):
            return None
        return self.generic_visit(node)

    def visit_AnnAssign(self, node):
        if ast.unparse(node.target) in {'self._rx_srtp', 'self._tx_srtp'}:
            return None
        return self.generic_visit(node)

    def visit_Expr(self, node):
        if isinstance(node.value, ast.Call) and ast.unparse(node.value.func) == 'self._setup_srtp':
            return None
        return self.generic_visit(node)

    def visit_If(self, node):
        if 'self._rx_srtp' in ast.unparse(node.test):
            return None
        return self.generic_visit(node)

    def visit_ExceptHandler(self, node):
        if node.type is not None and ast.unparse(node.type) == 'ConnectionError':
            # Media receivers were the only subscribers of this branch.
            if any('self._rtp_router' in ast.unparse(n) for n in node.body):
                node.body = [ast.Pass()]
        return self.generic_visit(node)


def transform(name, source):
    if name == 'sdp.py':
        # The SDP parser needs just the reserved RTP payload range, no packet
        # codec or PyAV module. Keep its mature parser / serializer intact.
        source = source.replace('from . import rtp\n', '')
        source = source.replace('rtp.FORBIDDEN_PAYLOAD_TYPES', 'range(72, 77)')
        return HEADER + source
    if name not in {'rtcpeerconnection.py', 'rtcdtlstransport.py'}:
        return HEADER + source
    if name == 'rtcdtlstransport.py':
        # Advertise the same SRTP extension for old aiortc peers, which
        # unconditionally require it even with an application-only SDP.
        # No SRTP session or native SRTP library is created on our side.
        start = source.index('SRTP_AEAD_AES_256_GCM =')
        end = source.index('\n\ndef certificate_digest', start)
        source = source[:start] + '''SRTP_PROFILES = [
    SRTPProtectionProfile(8, b"SRTP_AEAD_AES_256_GCM", 32, 12),
    SRTPProtectionProfile(7, b"SRTP_AEAD_AES_128_GCM", 16, 12),
    SRTPProtectionProfile(1, b"SRTP_AES128_CM_SHA1_80", 16, 14),
]
''' + source[end:]
        tree = DataOnlyDtls().visit(ast.parse(source))
    else:
        tree = DataOnlyPeer().visit(ast.parse(source))
    tree.body.insert(0, ast.ImportFrom(module='__future__', names=[ast.alias(name='annotations')], level=0))
    ast.fix_missing_locations(tree)
    generated = HEADER + ast.unparse(tree) + '\n'
    compile(generated, name, 'exec')
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path, help='aiortc 1.15.0 package directory')
    parser.add_argument('--license', required=True, type=Path, help='upstream BSD-3-Clause LICENSE')
    parser.add_argument('--output', type=Path, default=ROOT / 'src/buggcraft/hookup/_rtc')
    args = parser.parse_args()
    version = ast.parse((args.source / '__init__.py').read_text(encoding='utf-8'))
    if not any(isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__version__' for t in n.targets)
               and isinstance(n.value, ast.Constant) and n.value.value == '1.15.0' for n in version.body):
        parser.error('Only aiortc 1.15.0 has been reviewed for this extraction')
    manifest = {'project': 'aiortc', 'version': '1.15.0',
                'url': 'https://github.com/aiortc/aiortc/tree/1.15.0',
                'license': 'BSD-3-Clause', 'files': {}}
    generated = {}
    for name in FILES:
        original = (args.source / name).read_bytes()
        result = transform(name, original.decode('utf-8'))
        generated[name] = result
        manifest['files'][name] = {'upstream_sha256': hashlib.sha256(original).hexdigest(),
                                   'generated_sha256': hashlib.sha256(result.encode()).hexdigest()}
    # Refuse silently updating a different upstream source with the same
    # version. Source hashes are checked before any generated file is written.
    recorded = args.output / 'UPSTREAM.json'
    if recorded.is_file():
        previous = json.loads(recorded.read_text(encoding='utf-8'))
        for name in FILES:
            if previous['files'][name]['upstream_sha256'] != manifest['files'][name]['upstream_sha256']:
                parser.error('Upstream source hash changed: ' + name)
    args.output.mkdir(parents=True, exist_ok=True)
    for name, content in generated.items():
        (args.output / name).write_text(content, encoding='utf-8', newline='\n')
    (args.output / 'LICENSE').write_bytes(args.license.read_bytes())
    recorded.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(generated)} modules ({sum(len(c.encode()) for c in generated.values()):,} bytes)')


if __name__ == '__main__':
    main()
